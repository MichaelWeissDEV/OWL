"""Generate the CLI reference from the live Typer application.

Typer 0.27 ships its own copy of Click, which ``sphinx-click`` cannot read, so this tiny extension
introspects the command tree and writes ``reference/cli-commands.md`` before the build starts.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import typer


def _default(param: Any) -> str:
    default = getattr(param, "default", None)
    if default in (None, (), [], "", False) or callable(default):
        return ""
    return f"`{default}`"


def _usage(path: str, cmd: Any) -> str:
    parts = [path]
    if getattr(cmd, "commands", None):
        parts.append("COMMAND")
    if any(p.param_type_name == "option" for p in cmd.params):
        parts.append("[OPTIONS]")
    for p in cmd.params:
        if p.param_type_name == "argument":
            name = (p.metavar or p.name).upper()
            if p.nargs == -1 or getattr(p, "multiple", False):
                name += "..."
            parts.append(name if p.required else f"[{name}]")
    return " ".join(parts)


def _section(path: str, cmd: Any, level: int) -> list[str]:
    out = [f"{'#' * level} `{path}`", ""]
    help_text = (cmd.help or "").strip()
    if help_text:
        out += [help_text, ""]
    out += ["```text", f"Usage: {_usage(path, cmd)}", "```", ""]
    args = [p for p in cmd.params if p.param_type_name == "argument"]
    opts = [p for p in cmd.params if p.param_type_name == "option"]
    if args:
        out += ["**Arguments**", "", "| Argument | Required | Description |", "| --- | --- | --- |"]
        for p in args:
            help_ = (getattr(p, "help", "") or "").replace("|", "\\|")
            name = (p.metavar or p.name).upper() + ("..." if p.nargs == -1 else "")
            out.append(f"| `{name}` | {'yes' if p.required else 'no'} | {help_} |")
        out.append("")
    if opts:
        out += ["**Options**", "", "| Option | Default | Description |", "| --- | --- | --- |"]
        for p in opts:
            names = ", ".join(f"`{o}`" for o in [*p.opts, *p.secondary_opts])
            help_ = (p.help or "").replace("|", "\\|").replace("\n", " ")
            if getattr(p, "multiple", False):
                help_ = (help_ + " (repeatable)").strip()
            if getattr(p, "envvar", None):
                help_ += f" Env: `{p.envvar}`."
            out.append(f"| {names} | {_default(p)} | {help_} |")
        out.append("")
    return out


def _walk(path: str, cmd: Any, level: int) -> list[str]:
    lines = _section(path, cmd, level)
    for name in sorted(getattr(cmd, "commands", {}) or {}):
        sub = cmd.commands[name]
        lines += _walk(f"{path} {name}", sub, min(level + 1, 4))
    return lines


def generate(app: Any) -> None:
    from owl.cli import app as owl_app

    root = typer.main.get_command(owl_app)
    lines = [
        "<!-- generated by docs/_ext/owl_cli_docs.py - do not edit -->",
        "",
        "# Commands",
        "",
        "Generated from the installed CLI. Run `owl COMMAND --help` for the same information in a terminal.",
        "",
        "```text",
        f"Usage: {_usage('owl', root)}",
        "```",
        "",
        "| Command | Purpose |",
        "| --- | --- |",
    ]
    for name in sorted(root.commands):
        summary = (root.commands[name].help or "").strip().split("\n")[0]
        lines.append(f"| [`owl {name}`](#owl-{name.replace(' ', '-')}) | {summary} |")
    lines.append("")
    lines.append("```{contents}\n:local:\n:depth: 1\n```\n")
    for name in sorted(root.commands):
        lines += _walk(f"owl {name}", root.commands[name], 2)
    target = Path(app.srcdir) / "reference" / "cli-commands.md"
    new = "\n".join(lines) + "\n"
    if not target.exists() or target.read_text("utf-8") != new:
        target.write_text(new, "utf-8")


def setup(app: Any) -> dict[str, Any]:
    app.connect("builder-inited", generate)
    return {"parallel_read_safe": True}
