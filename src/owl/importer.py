"""Turning discovery candidates into stored skills: strict, defaults, interactive and dry-run.

Safety rules are *not* relaxed by any strategy: candidates with security problems (rejected)
or content that cannot be repaired are never stored as valid skills; incomplete material that stays
invalid is kept as a local **draft** instead.
"""

from __future__ import annotations

import re
from collections.abc import Callable
from dataclasses import dataclass, field

import yaml

from owl.discovery import Candidate, slugify
from owl.models import NAME_RE, Skill, normalize_labels, validate_skill
from owl.parsing import skill_from_markdown, split_frontmatter
from owl.stores.base import SkillStore

STRICT = "strict"
DEFAULTS = "defaults"
INTERACTIVE = "interactive"


@dataclass
class Fields:
    """The metadata an incomplete skill will get; values may be edited by the user."""

    name: str
    author: str
    version: str
    description: str
    tags: list[str]
    topics: list[str]
    generated: list[str] = field(default_factory=list)  #: fields OWL made up


@dataclass
class PlanItem:
    candidate: Candidate
    action: str  #: add | update | unchanged | skip | draft | reject
    skill: Skill | None = None
    generated: list[str] = field(default_factory=list)
    note: str = ""


def _first_paragraph(body: str) -> str:
    for block in re.split(r"\n\s*\n", body.strip()):
        lines = [
            ln.strip()
            for ln in block.splitlines()
            if ln.strip() and not ln.lstrip().startswith("#")
        ]
        text = " ".join(lines).strip()
        if text and not text.startswith(("```", "---")):
            return re.sub(r"\s+", " ", text)[:300]
    return ""


def suggest_fields(c: Candidate, default_author: str) -> Fields:
    """Defaults for an incomplete candidate (the source itself is never modified)."""
    fm, body, _ = split_frontmatter(c.text)
    generated: list[str] = []
    raw_name = fm.get("name") if isinstance(fm.get("name"), str) else ""
    name = raw_name if raw_name and NAME_RE.fullmatch(raw_name) and len(raw_name) <= 64 else ""
    if not name:
        name = slugify(raw_name or (c.origin.stem if c.origin.is_file() else c.origin.name))
        generated.append("name")
    description = fm.get("description") if isinstance(fm.get("description"), str) else ""
    description = (description or "").strip()
    if not description:
        description = _first_paragraph(body)
        if not description:
            description = f"Skill imported from {c.origin.name} (description generated by OWL)"
        generated.append("description")
    author = c.author if c.author and c.author != "local" else default_author
    nested: dict[str, object] = fm["metadata"] if isinstance(fm.get("metadata"), dict) else {}
    if not (fm.get("author") or nested.get("author") or c.extra.get("author")):
        generated.append("author")
    version = c.version or "0.0.0"
    if not (fm.get("version") or nested.get("version") or c.extra.get("version")):
        generated.append("version")
    return Fields(name, author, version, description, c.tags, c.topics, generated)


def build_skill(c: Candidate, fields: Fields) -> tuple[Skill, list[str]]:
    """Build a skill from the candidate's text and *fields*; returns it with its problems.

    A stored copy gets a valid frontmatter (name, description) while the body stays as it was.
    """
    fm, body, _ = split_frontmatter(c.text)
    if c.text.startswith("---") and not fm:
        # unparsable frontmatter: keep the text as body, do not guess
        fm, body = {}, c.text
    merged = {k: v for k, v in fm.items()}
    merged["name"] = fields.name
    merged["description"] = fields.description
    ordered = {"name": merged.pop("name"), "description": merged.pop("description"), **merged}
    header = yaml.safe_dump(ordered, sort_keys=False, allow_unicode=True, width=1000)
    content = f"---\n{header}---\n{body.lstrip(chr(10))}" if body else f"---\n{header}---\n"
    overlay = {
        "author": fields.author,
        "version": fields.version,
        "tags": normalize_labels(fields.tags),
        "topics": normalize_labels(fields.topics),
        **{k: v for k, v in c.extra.items() if k not in ("author", "version", "tags", "topics")},
    }
    if fields.generated:
        overlay["owl_generated"] = sorted(fields.generated)
    skill, problems = skill_from_markdown(
        content,
        default_author=fields.author,
        fallback_name=fields.name,
        files=c.files,
        overlay=overlay,
    )
    problems.extend(p for p in validate_skill(skill) if p not in problems)
    return skill, problems


def _existing_action(store: SkillStore | None, skill: Skill) -> str:
    if store is None:
        return "add"
    current = store.get(skill.author, skill.name)
    if current is None:
        return "add"
    return "unchanged" if current.sha256 == skill.sha256 else "update"


Prompter = Callable[[Candidate, Fields, int, int], "Fields | str | None"]


def build_plan(
    candidates: list[Candidate],
    *,
    mode: str,
    default_author: str,
    store: SkillStore | None = None,
    only: list[str] | None = None,
    prompter: Prompter | None = None,
) -> list[PlanItem]:
    """Decide what to do with every candidate.

    *prompter* (interactive mode) receives ``(candidate, suggested fields, index, total)`` and
    returns edited :class:`Fields`, ``"skip"``, ``"all"`` (accept defaults for the rest) or ``None``
    (abort). Valid candidates never prompt.
    """
    plan: list[PlanItem] = []
    accept_all = False
    incomplete = [c for c in candidates if c.status == "incomplete"]
    position = 0
    for c in candidates:
        if only and c.name not in only:
            continue
        if c.status == "rejected":
            plan.append(PlanItem(c, "reject", note="; ".join(c.problems)))
            continue
        if c.status == "valid" and c.skill is not None:
            plan.append(PlanItem(c, _existing_action(store, c.skill), c.skill))
            continue
        if c.status == "invalid":
            plan.append(
                PlanItem(c, "draft" if mode != STRICT else "skip", note="; ".join(c.problems))
            )
            continue
        # incomplete
        if mode == STRICT:
            plan.append(PlanItem(c, "skip", note="incomplete: " + "; ".join(c.problems)))
            continue
        position += 1
        fields = suggest_fields(c, default_author)
        if mode == INTERACTIVE and prompter is not None and not accept_all:
            answer = prompter(c, fields, position, len(incomplete))
            if answer is None:
                raise KeyboardInterrupt
            if answer == "skip":
                plan.append(PlanItem(c, "skip", note="skipped by user"))
                continue
            if answer == "all":
                accept_all = True
            elif isinstance(answer, Fields):
                fields = answer
        skill, problems = build_skill(c, fields)
        if problems:
            plan.append(PlanItem(c, "draft", generated=fields.generated, note="; ".join(problems)))
        else:
            plan.append(
                PlanItem(
                    c,
                    _existing_action(store, skill),
                    skill,
                    fields.generated,
                    "defaults: " + ", ".join(fields.generated) if fields.generated else "",
                )
            )
    return plan
